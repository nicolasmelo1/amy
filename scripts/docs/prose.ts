/**
 * The half of the documentation somebody writes, held to what the docs check says.
 *
 * The generated half cannot drift from the code; this half can, and it drifts
 * the same few ways every time: a hand-written count of members that the code
 * later changes, a phrase the catalogue of machine-written prose names, a page
 * that grows until nobody reads it, a code block that no longer compiles.
 * Each of those is a finding here, naming the file, the line and the rule,
 * instead of a comment a reviewer has to remember to write.
 *
 * What is never prose: a fenced block, inline code, a link's target, an HTML
 * comment or tag, and a generated block between its markers. A wholly
 * generated file, one that opens with the generator's banner, is not prose at
 * all; the hand-written words in it are checked where they are written.
 */

export interface Finding {
  readonly file: string;
  readonly line: number;
  readonly rule: string;
  readonly detail: string;
}

export function said(finding: Finding): string {
  return `${finding.file}:${finding.line} ${finding.rule}: ${finding.detail}`;
}

/** What kind of page a file is, which decides its limit and which checks read it. */
export type PageKind = "readme" | "guide" | "concept" | "example" | "page";

function kindOf(file: string): PageKind {
  if (file === "README.md") return "readme";
  if (/^docs\/guides\/[^/]+\.md$/.test(file)) return "guide";
  if (/^docs\/concepts\/[^/]+\.md$/.test(file)) return "concept";
  if (/^examples\/[^/]+\/README\.md$/.test(file)) return "example";
  return "page";
}

/** Prose characters a page may hold, code and generated blocks not counted. */
export const LIMITS: Readonly<Partial<Record<PageKind, number>>> = {
  readme: 2000,
  guide: 6000,
  concept: 8000,
  example: 1500,
};

/**
 * Every page a user reads, repository-relative.
 *
 * Plans, changesets, changelogs and `docs/design` are left out on purpose:
 * they are the argument behind a decision, kept as it was written.
 */
export function pagesInScope(root = ROOT): string[] {
  const found = ["README.md", "CONTRIBUTING.md"].filter((file) => fs.existsSync(path.join(root, file)));

  for (const relative of docFiles(path.join(root, "docs"))) {
    if (relative.startsWith("design/") || relative.startsWith("changelog/")) continue;
    if (WRITTEN_BY_SF.includes(`docs/${relative}`)) continue;
    found.push(`docs/${relative}`);
  }

  if (fs.existsSync(path.join(root, "examples/README.md"))) found.push("examples/README.md");

  for (const group of ["examples", "plugins", "packages"]) {
    const base = path.join(root, group);
    if (!fs.existsSync(base)) continue;
    for (const entry of fs.readdirSync(base).sort()) {
      const readme = `${group}/${entry}/README.md`;
      if (fs.existsSync(path.join(root, readme))) found.push(readme);
    }
  }

  return found;
}

/** Pages `sf init` writes from its own catalogue: generated, by a tool this check does not own. */
const WRITTEN_BY_SF = ["docs/rules.md"];

/** A file the generator writes whole, which carries its banner on the first line. */
function isWhollyGenerated(text: string): boolean {
  return text.startsWith("<!-- Generated by ");
}

// `sf docs` writes its own blocks into a page the same way, under its own
// prefix; what a generator writes is not prose, whichever generator it is.
const GENERATED_OPEN = /^\s*<!-- (?:amy|sf):generated ([a-z0-9-]+) -->\s*$/;
const GENERATED_CLOSE = /^\s*<!-- (?:amy|sf):end ([a-z0-9-]+) -->\s*$/;
const FENCE = /^\s*(`{3,}|~{3,})(.*)$/;

/**
 * The page with everything that is not prose blanked to spaces.
 *
 * Every line keeps its number, so a finding found in the result is reported
 * at the line a writer would open. A link's text stays, because it is read;
 * where it points does not, because it is not.
 */
function proseOf(text: string): string {
  const lines = text.split("\n");
  const block: Block = { frontmatter: lines[0]?.trim() === "---", fence: null, generated: null, comment: false };
  return lines.map((line, index) => proseLine(block, line, index)).join("\n");
}

/** Where the reader is, line to line: inside front matter, a fence, a generated block or a comment. */
interface Block {
  frontmatter: boolean;
  fence: string | null;
  generated: string | null;
  comment: boolean;
}

function proseLine(block: Block, line: string, index: number): string {
  if (block.frontmatter) return frontmatterLine(block, line, index);
  if (insideBlock(block, line)) return " ".repeat(line.length);
  if (!block.comment && opensBlock(block, line)) return " ".repeat(line.length);
  return outsideComments(block, line);
}

/** Front matter is prose only in its title and description, which a reader sees. */
function frontmatterLine(block: Block, line: string, index: number): string {
  if (index > 0 && line.trim() === "---") {
    block.frontmatter = false;
    return " ".repeat(line.length);
  }
  const field = /^(title|description):\s*(.*)$/.exec(line);
  if (!field) return " ".repeat(line.length);
  const value = field[2] ?? "";
  return `${" ".repeat(line.length - value.length)}${unquote(value)}`;
}

/** Whether the line is inside a fence or a generated block, closing it on its last line. */
function insideBlock(block: Block, line: string): boolean {
  if (block.generated !== null) {
    if (GENERATED_CLOSE.exec(line)?.[1] === block.generated) block.generated = null;
    return true;
  }
  if (block.fence === null) return false;
  const closing = FENCE.exec(line);
  if (closing && closing[1]!.startsWith(block.fence) && closing[2]!.trim() === "") block.fence = null;
  return true;
}

/** Whether the line opens a fence or a generated block. */
function opensBlock(block: Block, line: string): boolean {
  const fence = FENCE.exec(line);
  if (fence) {
    block.fence = fence[1]!;
    return true;
  }
  const open = GENERATED_OPEN.exec(line);
  if (!open) return false;
  block.generated = open[1]!;
  return true;
}

/** The line with any HTML comment blanked, carrying an unclosed one to the next line. */
function outsideComments(block: Block, line: string): string {
  let kept = line;
  if (block.comment) {
    const end = kept.indexOf("-->");
    if (end === -1) return " ".repeat(line.length);
    kept = " ".repeat(end + 3) + kept.slice(end + 3);
    block.comment = false;
  }
  const start = kept.indexOf("<!--");
  if (start !== -1 && kept.indexOf("-->", start) === -1) {
    kept = kept.slice(0, start) + " ".repeat(kept.length - start);
    block.comment = true;
  }
  return inlineProse(kept);
}

function unquote(value: string): string {
  const trimmed = value.trim();
  if ((trimmed.startsWith('"') && trimmed.endsWith('"')) || (trimmed.startsWith("'") && trimmed.endsWith("'"))) {
    return ` ${trimmed.slice(1, -1)} `;
  }
  return value;
}

/** One line, with its code, comments, tags and link targets blanked. */
function inlineProse(line: string): string {
  const blank = (match: string) => " ".repeat(match.length);
  return line
    .replace(/<!--.*?-->/g, blank)
    .replace(/(`+)[\s\S]*?\1/g, blank)
    .replace(/^\s*\[[^\]]+\]:\s*\S+.*$/, blank)
    .replace(/\]\([^)]*\)/g, (match) => `]${" ".repeat(match.length - 1)}`)
    .replace(/<\/?[a-zA-Z][^>]*>/g, blank)
    .replace(/https?:\/\/\S+/g, blank);
}

/** The line a character offset falls on, counting from one. */
function lineAt(text: string, offset: number): number {
  let line = 1;
  for (let index = 0; index < offset; index += 1) if (text.charCodeAt(index) === 10) line += 1;
  return line;
}

/** Emphasis is read as the word it emphasises, so `**ten** gates` is still a count. */
function plain(prose: string): string {
  return prose.replace(/[*_]/g, " ");
}

const NUMBER_WORDS = [
  "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten", "eleven", "twelve",
  "thirteen", "fourteen", "fifteen", "sixteen", "seventeen", "eighteen", "nineteen", "twenty",
  "thirty", "forty", "fifty", "sixty", "seventy", "eighty", "ninety", "hundred", "thousand", "dozen",
];

/**
 * Words ending in `s` that follow a number without being what it counts.
 *
 * A verb is the usual one: "Node 22 runs it". Missing one here is a false
 * finding a writer rewords around; that is cheaper than a count that ships.
 */
const NOT_PLURAL = new Set([
  "this", "its", "was", "has", "does", "is", "as", "yes", "plus", "always", "perhaps", "less",
  "across", "unless", "thus", "whereas", "besides", "sometimes", "afterwards", "towards", "goes",
  "runs", "says", "takes", "makes", "needs", "adds", "gets", "sets", "uses", "reads", "writes",
  "holds", "keeps", "means", "moves", "comes", "becomes", "seems", "stays", "fails", "passes",
  "ships", "works", "returns", "starts", "ends", "asks", "answers", "lists", "names", "shows",
]);

function isPlural(word: string): boolean {
  const lower = word.toLowerCase();
  if (lower.length < 3 || !lower.endsWith("s")) return false;
  if (/(ss|us|is)$/.test(lower)) return false;
  return !NOT_PLURAL.has(lower);
}

/**
 * Every hand-written count: a number or a number-word directly before a plural noun.
 *
 * Wherever it is, in a heading or a sentence. The count that is true is the
 * one generated from what it counts, between the generator's markers, and
 * nothing else is exempt.
 */
export function countsIn(file: string, text: string): Finding[] {
  if (isWhollyGenerated(text)) return [];
  const prose = plain(proseOf(text));
  const found: Finding[] = [];
  // eslint-disable-next-line security/detect-non-literal-regexp -- built from NUMBER_WORDS, a constant in this file
  const pattern = new RegExp(`(?<![\\w.\\-/#$])(\\d+|${NUMBER_WORDS.join("|")})\\s+([A-Za-z]+)\\b`, "gi");

  for (const match of prose.matchAll(pattern)) {
    const word = match[2]!;
    if (!isPlural(word)) continue;
    found.push({
      file,
      line: lineAt(prose, match.index),
      rule: "count",
      detail: `"${match[1]} ${word}" is a hand-written count; generate it from what it counts, or say it with no number`,
    });
  }

  return found;
}

interface Slop {
  readonly name: string;
  readonly pattern: RegExp;
}

function words(list: readonly string[]): Slop[] {
  return list.map((phrase) => ({
    name: phrase,
    // eslint-disable-next-line security/detect-non-literal-regexp -- the phrases are SLOP's own constants, escaped of nothing they need
    pattern: new RegExp(`\\b${phrase.replace(/'/g, "['’]").replace(/ /g, "\\s+")}\\b`, "gi"),
  }));
}

/**
 * The patterns the catalogue of machine-written prose names, and amy's own taglines.
 *
 * See https://en.wikipedia.org/wiki/Wikipedia:Signs_of_AI_writing. The arrow,
 * an exclamation mark, emoji, curly quotes and "deliberately" are allowed by
 * decision, so nothing here names them.
 */
export const SLOP: readonly Slop[] = [
  { name: "em dash", pattern: /—/g },
  { name: "en dash between spaces", pattern: / – /g },
  ...words(["not just", "isn't just", "not only", "not merely"]),
  ...words([
    "delve", "tapestry", "testament", "pivotal", "crucial", "intricacies", "meticulous", "vibrant",
    "garner", "showcase", "highlighting", "underscore", "fostering", "enhance", "leverage",
    "multifaceted", "seamless", "robust", "powerful", "landscape", "serves as", "stands as", "boasts",
  ]),
  ...words([
    "quietly", "genuinely", "simply", "truly", "essentially", "actually", "leave it running",
    "the long part", "somewhere else", "the real point", "the whole point", "worth pausing", "load-bearing",
  ]),
];

/** Every listed slop pattern in a page's prose, by file, line and pattern. */
export function slopIn(file: string, text: string): Finding[] {
  if (isWhollyGenerated(text)) return [];
  return slopInProse(file, proseOf(text));
}

function slopInProse(file: string, prose: string): Finding[] {
  const found: Finding[] = [];
  for (const slop of SLOP) {
    for (const match of prose.matchAll(slop.pattern)) {
      found.push({ file, line: lineAt(prose, match.index), rule: "slop", detail: `"${slop.name}"` });
    }
  }
  return found.sort((a, b) => a.line - b.line);
}

const REFERENCE_OPEN = "<!-- amy:generated reference -->";

/** How many prose characters a page holds: whitespace runs read as one space. */
function proseSize(text: string, kind: PageKind): number {
  if (isWhollyGenerated(text)) return 0;
  const intro = kind === "example" && text.includes(REFERENCE_OPEN) ? text.slice(0, text.indexOf(REFERENCE_OPEN)) : text;
  return proseOf(intro)
    .replace(/[#|>]/g, " ")
    .replace(/\s+/g, " ")
    .trim().length;
}

/** A page over its kind's limit, naming the page, its size and the limit. */
export function limitIn(file: string, text: string): Finding[] {
  const kind = kindOf(file);
  const limit = LIMITS[kind];
  if (limit === undefined) return [];
  const size = proseSize(text, kind);
  if (size <= limit) return [];
  return [{ file, line: 1, rule: "limit", detail: `${size} prose characters, over the ${kind} limit of ${limit}` }];
}

/** An example's introduction opens with one sentence saying what it does. */
export function exampleOpeningIn(file: string, text: string): Finding[] {
  const intro = text.includes(REFERENCE_OPEN) ? text.slice(0, text.indexOf(REFERENCE_OPEN)) : text;
  const lines = intro.split("\n");
  const title = lines.findIndex((line) => /^# /.test(line));
  if (title === -1) return [{ file, line: 1, rule: "example", detail: "has no `# ` title for its introduction to open under" }];

  let start = title + 1;
  while (start < lines.length && lines[start]!.trim() === "") start += 1;
  let end = start;
  while (end < lines.length && lines[end]!.trim() !== "") end += 1;

  const paragraph = lines.slice(start, end).join(" ").replace(/`[^`]*`/g, "code").replace(/\s+/g, " ").trim();
  const sentences = paragraph.split(/(?<=[.!?])\s+(?=[A-Z`"[(])/).filter(Boolean);
  if (paragraph === "" || /^[#<|`>-]/.test(paragraph)) {
    return [{ file, line: start + 1, rule: "example", detail: "the introduction opens with something other than a sentence saying what it does" }];
  }
  if (sentences.length !== 1 || !/[.!?]$/.test(paragraph)) {
    return [{ file, line: start + 1, rule: "example", detail: `the introduction's first paragraph is ${sentences.length} sentences; open with one saying what it does` }];
  }
  return [];
}

/** A glossary term, and the anchor a guide links it by. */
export interface Term {
  readonly term: string;
  readonly anchor: string;
}

const GLOSSARY = "docs/concepts/glossary.md";

/** The glossary's `##` headings, each one a term. */
function glossaryTerms(text: string): Term[] {
  return headings(text)
    .filter((heading) => heading.depth === 2)
    .map((heading) => ({ term: heading.title.toLowerCase(), anchor: heading.slug }));
}

/**
 * A guide's first use of each glossary term, where it is not a link to that term.
 *
 * Headings and the title are not a use: a heading cannot carry the link well,
 * and the sentence under it can. A term that appears inside a longer term's
 * link is used there too, which is the reader's experience of it.
 */
export function unlinkedTermsIn(file: string, text: string, terms: readonly Term[]): Finding[] {
  if (isWhollyGenerated(text)) return [];
  // The title cannot carry a link any more than a heading can, so the front
  // matter is not a use either. Every blanked line keeps its length, so an
  // offset here is an offset in the page, where the links are read.
  const raw = text.split("\n");
  const close = raw[0]?.trim() === "---" ? raw.findIndex((line, index) => index > 0 && line.trim() === "---") : -1;
  const prose = proseOf(text)
    .split("\n")
    .map((line, index) => (index <= close || /^\s*#/.test(raw[index] ?? "") ? " ".repeat(line.length) : line))
    .join("\n");

  // The link spans are read from the raw page, where the targets still are.
  const links: { from: number; to: number; target: string }[] = [];
  let offset = 0;
  for (const line of raw) {
    for (const match of line.matchAll(/\[([^\]]*)\]\(([^)]*)\)/g)) {
      links.push({ from: offset + match.index + 1, to: offset + match.index + 1 + match[1]!.length, target: match[2]! });
    }
    offset += line.length + 1;
  }

  const found: Finding[] = [];
  for (const { term, anchor } of terms) {
    // eslint-disable-next-line security/detect-non-literal-regexp -- a glossary heading, escaped character by character above
    const pattern = new RegExp(`\\b${term.replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replace(/ /g, "\\s+")}(s|es)?\\b`, "i");
    const match = pattern.exec(prose);
    if (!match) continue;
    const link = links.find((one) => one.from <= match.index && match.index < one.to);
    if (link && link.target.endsWith(`glossary.md#${anchor}`)) continue;
    found.push({
      file,
      line: lineAt(prose, match.index),
      rule: "glossary",
      detail: `the first use of "${term}" does not link to glossary.md#${anchor}`,
    });
  }
  return found;
}

/**
 * Design notes no longer argued for anywhere, each naming what replaced it.
 *
 * A note stays in `docs/design`, kept as it was written; listing it here is
 * how it stops needing a link from a page a user reads.
 */
const SUPERSEDED: Readonly<Record<string, string>> = {};

/**
 * Every design note no page a user reads links to, and that is not listed as superseded.
 *
 * What a plan delivered is a note in `docs/design`; a note nothing outside it
 * links to is a decision nobody reading the docs will find.
 */
export function unreachableNotes(
  notes: readonly string[],
  pages: Readonly<Record<string, string>>,
  superseded: Readonly<Record<string, string>>,
  exists: (file: string) => boolean,
): Finding[] {
  const linked = linkedFrom(pages);
  return notes.flatMap((note) => {
    const replacement = superseded[path.posix.basename(note)];
    if (replacement !== undefined) {
      return exists(replacement) ? [] : [designFinding(note, `is listed as superseded by ${replacement}, which does not exist`)];
    }
    if (linked.has(note)) return [];
    return [designFinding(note, "no page a user reads links to this note; link it where its decision is described, or list it in SUPERSEDED naming its replacement")];
  });
}

/** Every repository path a page outside docs/design and plans links to, resolved from that page. */
function linkedFrom(pages: Readonly<Record<string, string>>): Set<string> {
  const linked = new Set<string>();
  for (const [file, text] of Object.entries(pages)) {
    if (file.startsWith("docs/design/") || file.startsWith("plans/")) continue;
    for (const target of linkTargets(text)) {
      const local = target.replace(/#.*$/, "");
      if (local === "" || /^[a-z]+:/.test(local)) continue;
      linked.add(path.posix.normalize(path.posix.join(path.posix.dirname(file), local)));
    }
  }
  return linked;
}

/** Where every markdown link and every `href` on a page points. */
function linkTargets(text: string): string[] {
  return [...text.matchAll(/\]\(([^)\s]+)\)|href="([^"]+)"/g)].map((match) => match[1] ?? match[2] ?? "");
}

function designFinding(note: string, detail: string): Finding {
  return { file: note, line: 1, rule: "design", detail };
}

/** The nav groups, by the directory each one reads. */
interface NavGroup {
  readonly group: string;
  readonly dir: string;
}

export function navGroups(text: string): NavGroup[] {
  return (yaml.parse(text) as NavGroup[]) ?? [];
}

/**
 * The root README held to being a summary.
 *
 * It points at every part of the documentation, every section ends in the
 * link that says more, installing is at most two commands, it names the
 * harnesses it runs on, it points agents at amy's skills, and it shows the
 * logo. Whether it reads well is review's; these are the proxies for it.
 */
export function readmeProblems(text: string, nav: readonly NavGroup[]): Finding[] {
  const lines = text.split("\n");
  const targets = linkTargets(text);
  const sections = lines.flatMap((line, index) => (/^## /.test(line) ? [index] : []));
  return [
    ...navProblems(targets, nav),
    ...sectionProblems(lines, sections),
    ...installProblems(lines, sections),
    ...presenceProblems(text, targets),
  ].map(([line, detail]) => ({ file: "README.md", line, rule: "readme", detail }));
}

type Said = readonly [line: number, detail: string];

function navProblems(targets: readonly string[], nav: readonly NavGroup[]): Said[] {
  return nav
    .filter((group) => !targets.some((target) => target.replace(/^\.\//, "").startsWith(`docs/${group.dir}/`)))
    .map((group) => [1, `links nothing in the nav group "${group.group}" (docs/${group.dir}/)`]);
}

/** Each `##` section's last non-blank line has to carry the link that says more. */
function sectionProblems(lines: readonly string[], sections: readonly number[]): Said[] {
  return sections.flatMap((start, order): Said[] => {
    const body = lines
      .slice(start + 1, sections[order + 1] ?? lines.length)
      .map((line) => line.trim())
      .filter((line) => line !== "" && line !== "---");
    const last = body[body.length - 1] ?? "";
    return /\]\([^)]+\)|href="/.test(last) ? [] : [[start + 1, `the section "${lines[start]!.slice(3)}" does not end in a link`]];
  });
}

/** The install section's first command block holds at most two commands. */
function installProblems(lines: readonly string[], sections: readonly number[]): Said[] {
  const install = sections.find((start) => /install/i.test(lines[start]!));
  if (install === undefined) return [[1, "has no install section"]];
  const open = lines.findIndex((line, index) => index > install && /^```(sh|bash|shell)?\s*$/.test(line));
  if (open === -1) return [[install + 1, "the install section has no command block"]];
  const close = lines.findIndex((line, index) => index > open && /^```\s*$/.test(line));
  const commands = lines.slice(open + 1, close).filter((line) => line.trim() !== "" && !line.trim().startsWith("#"));
  return commands.length > 2 ? [[open + 1, `installs in ${commands.length} commands; at most two`]] : [];
}

/** The harnesses it runs on, the skills for agents, and the logo. */
function presenceProblems(text: string, targets: readonly string[]): Said[] {
  const said: Said[] = ["Claude Code", "Codex", "Hermes"]
    .filter((harness) => !text.includes(harness))
    .map((harness) => [1, `does not name ${harness}`]);
  if (!targets.some((target) => /skills/.test(target))) said.push([1, "does not link amy's skills for agents"]);
  if (!/src="(\.\/)?assets\/logo\.png"|\]\((\.\/)?assets\/logo\.png\)/.test(text)) said.push([1, "does not show assets/logo.png"]);
  return said;
}

/**
 * A code fence on a guide or concept page, and how the check treats it.
 *
 * Every `ts` fence is typechecked. One opts out only by
 * `<!-- amy:untyped REASON -->` on the line above it; one names the file it
 * is with `<!-- amy:file NAME -->`, or `<!-- amy:scaffold NAME -->` when it
 * is the file `amy workflow new` writes, so blocks on one page can import
 * each other the way the files they show do.
 */
interface Fence {
  readonly file: string;
  /** The line the fence opens on, counting from one. */
  readonly line: number;
  readonly lang: string;
  readonly info: string;
  readonly code: string;
  readonly marker?: { readonly kind: "untyped" | "file" | "scaffold"; readonly value: string };
}

const MARKER = /^\s*<!-- amy:(untyped|file|scaffold)\s+(.*?)\s*-->\s*$/;

function fencesIn(file: string, text: string): Fence[] {
  const lines = text.split("\n");
  const block: Block = { frontmatter: false, fence: null, generated: null, comment: false };
  const fences: Fence[] = [];

  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index]!;
    if (insideGenerated(block, line)) continue;
    const fence = FENCE.exec(line);
    if (!fence) continue;
    const end = fenceEnd(lines, index, fence[1]!);
    fences.push(fenceAt(file, lines, index, end, fence[2]!.trim()));
    index = end;
  }

  return fences;
}

/** Whether the line is in, or opens, a generated block, which holds no fence a writer wrote. */
function insideGenerated(block: Block, line: string): boolean {
  if (block.generated !== null) {
    if (GENERATED_CLOSE.exec(line)?.[1] === block.generated) block.generated = null;
    return true;
  }
  const open = GENERATED_OPEN.exec(line);
  if (open) block.generated = open[1]!;
  return open !== null;
}

/** The line that closes the fence opened at `index`, or the end of the page. */
function fenceEnd(lines: readonly string[], index: number, ticks: string): number {
  let end = index + 1;
  while (end < lines.length && !closesFence(lines[end]!, ticks)) end += 1;
  return end;
}

function closesFence(line: string, ticks: string): boolean {
  const trimmed = line.trim();
  return trimmed.startsWith(ticks) && trimmed.slice(ticks.length).trim() === "";
}

function fenceAt(file: string, lines: readonly string[], index: number, end: number, info: string): Fence {
  const marker = markerAbove(lines, index);
  return {
    file,
    line: index + 1,
    lang: info.split(/\s+/)[0] ?? "",
    info,
    code: lines.slice(index + 1, end).join("\n"),
    ...(marker ? { marker } : {}),
  };
}

/** The `amy:` marker on the nearest non-blank line above a fence, if that line is one. */
function markerAbove(lines: readonly string[], index: number): Fence["marker"] {
  let above = index - 1;
  while (above >= 0 && lines[above]!.trim() === "") above -= 1;
  const marker = above >= 0 ? MARKER.exec(lines[above]!) : null;
  return marker ? { kind: marker[1] as "untyped" | "file" | "scaffold", value: marker[2]! } : undefined;
}

/** Pages that teach no code, each with the reason it has none. Nothing else is exempt. */
const PROSE_ONLY: Readonly<Record<string, string>> = {
  "docs/concepts/glossary.md": "a list of terms, each a sentence",
  "docs/guides/project-workflow-plugin.md": "tells the three apart before any of them is written",
  "docs/guides/install-a-plugin.md": "commands and config, which are not TypeScript",
  "docs/guides/what-a-project-is.md": "what a project is, before any code",
  "docs/guides/the-chat.md": "what happens in a chat, which is configured rather than written",
  "docs/concepts/budgets.md": "what an agent may spend, configured rather than written",
  "docs/concepts/the-queue.md": "how work waits, which a workflow never touches in code",
  "docs/concepts/mad-and-bep.md": "the opinions every workflow and every project are held to, before any code",
};

const RELABELLED = new Set(["js", "javascript", "mjs", "cjs", "typescript", "tsx", "jsx", "mts", "cts"]);

/** Whether a page is one whose `ts` fences are checked. */
export function isCheckedPage(file: string): boolean {
  return /^docs\/(guides|concepts)\/[^/]+\.md$/.test(file);
}

/**
 * What is wrong with a checked page's fences, before anything is compiled.
 *
 * A page yielding no checked block fails, so removing its fences or
 * relabelling them is not a way past the check; a block opts out only by the
 * named marker, never by its language or a comment inside it.
 */
export function fenceProblems(file: string, text: string): Finding[] {
  if (!isCheckedPage(file)) return [];
  const fences = fencesIn(file, text);
  const checked = fences.filter((fence) => fence.lang === "ts" && fence.marker?.kind !== "untyped");
  return [...fences.flatMap(labelProblems), ...coverageProblems(file, checked)].map(([line, detail]) => ({ file, line, rule: "fence", detail }));
}

/** A fence that hides TypeScript from the check by its label, its info string or a comment inside it. */
function labelProblems(fence: Fence): Said[] {
  const said: Said[] = [];
  if (RELABELLED.has(fence.lang.toLowerCase())) said.push([fence.line, `a \`${fence.lang}\` fence; TypeScript on this page is labelled \`ts\``]);
  if (fence.lang === "" && /^\s*(import|export|const|function|interface|type)\b/m.test(fence.code)) {
    said.push([fence.line, "an unlabelled fence holding TypeScript; label it `ts`"]);
  }
  if (fence.lang !== "ts") return said;
  if (fence.info !== "ts") said.push([fence.line, `\`${fence.info}\` is not how a block opts out; use <!-- amy:untyped REASON -->`]);
  if (/@ts-(nocheck|ignore|expect-error)/.test(fence.code)) said.push([fence.line, "a block silenced from inside; use <!-- amy:untyped REASON --> above it"]);
  if (fence.marker?.kind === "untyped" && fence.marker.value.trim() === "") said.push([fence.line, "an untyped block names no reason"]);
  return said;
}

/** A page that teaches code shows a checked block; a page listed as prose only shows none. */
function coverageProblems(file: string, checked: readonly Fence[]): Said[] {
  if (PROSE_ONLY[file] !== undefined) {
    return checked.length > 0 ? [[checked[0]!.line, "is listed in PROSE_ONLY and has a ts block; take it off the list"]] : [];
  }
  return checked.length === 0 ? [[1, "yields no checked ts block; a page that teaches code shows it, or is listed in PROSE_ONLY with its reason"]] : [];
}

/**
 * Every prose finding in the repository, in the order a writer would fix them.
 *
 * The typecheck of the fences is not here: it compiles the core, so it runs
 * in `scripts/docs/tests/examples.test.ts` rather than on every docs check.
 */
export function proseProblems(root = ROOT): Finding[] {
  const read = (file: string) => fs.readFileSync(path.join(root, file), "utf8");
  const pages = pagesInScope(root);
  const texts: Record<string, string> = Object.fromEntries(pages.map((file) => [file, read(file)]));
  const glossary = fs.existsSync(path.join(root, GLOSSARY)) ? glossaryTerms(read(GLOSSARY)) : [];
  const found: Finding[] = [];

  for (const file of pages) {
    const text = texts[file]!;
    found.push(...countsIn(file, text), ...slopIn(file, text), ...limitIn(file, text), ...fenceProblems(file, text));
    if (kindOf(file) === "example") found.push(...exampleOpeningIn(file, text));
    if (kindOf(file) === "guide") found.push(...unlinkedTermsIn(file, text, glossary));
  }

  if (texts["README.md"] !== undefined) found.push(...readmeProblems(texts["README.md"], navGroups(read("docs/nav.yaml"))));
  found.push(...aboutProblems(root));

  const notes = fs.readdirSync(path.join(root, "docs/design")).filter((name) => name.endsWith(".md")).map((name) => `docs/design/${name}`);
  found.push(...unreachableNotes(notes, texts, SUPERSEDED, (file) => fs.existsSync(path.join(root, file))));

  return found;
}

/**
 * A plugin's `amy.about`: the paragraph on when to use it, which its README shows.
 *
 * It is the one piece of a plugin README somebody writes, so it is held to
 * the same prose rules as a page, where it is written.
 */
function aboutProblems(root = ROOT): Finding[] {
  const found: Finding[] = [];
  const base = path.join(root, "plugins");
  if (!fs.existsSync(base)) return found;

  for (const entry of fs.readdirSync(base).sort()) {
    const manifest = `plugins/${entry}/package.json`;
    if (!fs.existsSync(path.join(root, manifest))) continue;
    const parsed = JSON.parse(fs.readFileSync(path.join(root, manifest), "utf8")) as { name?: string; private?: boolean; amy?: { about?: unknown } };
    const about = parsed.amy?.about;
    if (typeof about !== "string" || about.trim() === "") {
      found.push({ file: manifest, line: 1, rule: "about", detail: `${parsed.name ?? entry} has no amy.about saying when to use it` });
      continue;
    }
    found.push(...countsIn(manifest, about).map((one) => ({ ...one, line: 1 })), ...slopInProse(manifest, about).map((one) => ({ ...one, line: 1 })));
  }
  return found;
}

/**
 * Typechecks every checked `ts` fence against the core as it is in this repository.
 *
 * Each block is compiled where its page puts it: a block naming a file sits
 * beside the other named blocks of its page, as they stand at that point of
 * the page (or as they are first shown, if later), so `./decide.ts` resolves
 * to the block that shows it. An unnamed block is a module of its own. The
 * packages resolve to their source, as the repository's own tests do.
 */
export async function fenceTypeErrors(pages: Readonly<Record<string, string>>, root = ROOT): Promise<Finding[]> {
  const ts = (await import("typescript")).default;
  const config = ts.readConfigFile(path.join(root, "tsconfig.tests.json"), ts.sys.readFile);
  const options = {
    ...ts.parseJsonConfigFileContent(config.config, ts.sys, root).options,
    noEmit: true,
    allowImportingTsExtensions: true,
    composite: false,
    incremental: false,
    declaration: false,
    declarationMap: false,
    sourceMap: false,
    noUnusedLocals: false,
    noUnusedParameters: false,
  };

  const { virtual, owners } = placedBlocks(pages, path.join(root, ".doc-blocks"));
  const host = ts.createCompilerHost(options);
  const readFile = host.readFile.bind(host);
  const fileExists = host.fileExists.bind(host);
  const directoryExists = host.directoryExists?.bind(host) ?? ts.sys.directoryExists;
  const getSourceFile = host.getSourceFile.bind(host);
  const blocks = path.join(root, ".doc-blocks");
  host.readFile = (name) => virtual.get(name) ?? readFile(name);
  host.fileExists = (name) => virtual.has(name) || fileExists(name);
  host.directoryExists = (name) => name.startsWith(blocks) || directoryExists(name);
  host.getSourceFile = (name, language, onError, create) => {
    const code = virtual.get(name);
    return code === undefined ? getSourceFile(name, language, onError, create) : ts.createSourceFile(name, code, language, true);
  };

  const program = ts.createProgram([...owners.keys()], options, host);
  return [...owners].flatMap(([name, fence]) => {
    const source = program.getSourceFile(name);
    if (!source) return [];
    return [...program.getSyntacticDiagnostics(source), ...program.getSemanticDiagnostics(source)].map((diagnostic) => ({
      file: fence.file,
      line: fence.line + 1 + (diagnostic.start === undefined ? 0 : source.getLineAndCharacterOfPosition(diagnostic.start).line),
      rule: "typecheck",
      detail: ts.flattenDiagnosticMessageText(diagnostic.messageText, " "),
    }));
  });
}

/**
 * Every checked block as a file in a directory of its own, beside the named
 * blocks of its page as they stand at that block: each one's last version so
 * far, or the first one the page shows, if the page has not reached it yet.
 */
function placedBlocks(pages: Readonly<Record<string, string>>, base: string): { virtual: Map<string, string>; owners: Map<string, Fence> } {
  const virtual = new Map<string, string>();
  const owners = new Map<string, Fence>();

  for (const [file, text] of Object.entries(pages)) {
    if (!isCheckedPage(file)) continue;
    const fences = fencesIn(file, text).filter((fence) => fence.lang === "ts" && fence.marker?.kind !== "untyped");
    const named = fences.map((fence, at) => [at, fence] as const).filter(([, fence]) => nameOf(fence) !== undefined);

    for (const [index, fence] of fences.entries()) {
      const dir = path.join(base, file.replace(/[/.]/g, "_"), String(index));
      const latest = new Map<string, Fence>();
      for (const [at, one] of named) if (at <= index || !latest.has(nameOf(one)!)) latest.set(nameOf(one)!, one);
      for (const [name, one] of latest) virtual.set(path.join(dir, name), one.code);
      const own = path.join(dir, nameOf(fence) ?? "block.ts");
      virtual.set(own, fence.code);
      owners.set(own, fence);
    }
  }

  return { virtual, owners };
}

/** The file a block says it is, if it says. */
function nameOf(fence: Fence): string | undefined {
  return fence.marker?.kind === "file" || fence.marker?.kind === "scaffold" ? fence.marker.value : undefined;
}
